# 形状不合格：抽出来的东西不该带这些"连接词壳"——它们进检索式就是噪音
BAD_PREFIX = ("方向是", "对象是", "题目是", "主题是", "课题是", "选的是", "的是", "这块", "方向选",
              "一个", "一种", "一批")
BAD_SUFFIX = ("这个方向", "这块", "的方向")
PUNCT = "，。、；！？,.;!?：:（）()《》“”\"' \t"


def shape_ok(topic: str) -> bool:
    """形状判据：非空、不含句读、不以连接词壳开头/结尾。"""
    if not topic or any(ch in PUNCT for ch in topic):
        return False
    return not (topic.startswith(BAD_PREFIX) or topic.endswith(BAD_SUFFIX))
