"""教学维度的**可机检最小形状**：这条回复里有没有留下一个「由学生自己动手完成的下一步」。

为什么不问评委"这条有没有教学价值"：轮 153 之前的锚点对实测里，把题写成"回复是否推动/鼓励学生"
会**奖励纯鼓励话术、方向倒着走**（已知差的回复得 1 分，用尽约束的好回复得 0 分）。
所以这一维只落在**回答里可核对的动作**上：句子得是"你 + 一个具体动作"，
而不是"我这就去查"（动作主语是助手）或"你一定可以的"（没有动作）。

依据：Teaching-over-Solving（2606.16206）答对率几乎不预测教学价值；AutoTutor 一脉靠显式的
学生模型。这里只做最小的一步——先把"有没有留作业"变成机器数得出的量，不做学生模型。
"""
from __future__ import annotations

import re

# 学生作为动作主体的形状：你(+时间/情态) + 动手
_AGENTIVE = re.compile(
    r"你(?:自己|这边|那儿)?(?:这|本|下)?(?:周|周里|天|几天|月)?"
    r"(?:先|要|得|应该|该|可以|不妨|试着|回去|去|拿|把|读|跑|复现|列|写|整理|标注|对比|查|做|爬|标|记|看|搭|试)"
)
# 光有"你+动词"还不够，句子里得有一个**可交付**的动作词（"你可以的"里没有）
_DELIVERABLE = re.compile(
    r"(读|跑|复现|列|写|整理|标注|对比|查|做|爬|标|记|看|搭|试|筛|数|算|画|交|发)")
_CORE = re.compile(r"[\u4e00-\u9fffA-Za-z0-9]")
_SENT_SPLIT = re.compile(r"[。！？!?;\n]|(?:[，,]\s*(?=你))")

MIN_CHARS = 10        # 短于这个长度的"你先看看"多半是过场句


def student_next_step(reply: str) -> str:
    """返回回复里那条「学生自己动手的下一步」原句（逐字）；没有则空串。

    逐字返回是刻意的：这条量具将来要进 A/B 与验收台账，摘录必须能回连到被评文本本身
    （评委"做到了"却不给逐字摘录，就是轮 153 之前那套读数作废的根因之一）。
    """
    for sent in _SENT_SPLIT.split(reply or ""):
        s = sent.strip("，、 ：")
        if not s or len(_CORE.findall(s)) < MIN_CHARS:
            continue
        if _AGENTIVE.search(s) and _DELIVERABLE.search(s):
            return s
    return ""
